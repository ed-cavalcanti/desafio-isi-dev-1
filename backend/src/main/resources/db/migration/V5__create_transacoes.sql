CREATE TABLE transacoes (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    clube_id INTEGER NOT NULL,
    jogador_id INTEGER NOT NULL,
    jogador_nome VARCHAR(100) NOT NULL,
    tipo VARCHAR(7) NOT NULL,
    valor DECIMAL(8,2) NOT NULL,
    taxa DECIMAL(8,2) NOT NULL,
    multa DECIMAL(8,2) NOT NULL,
    lucro DECIMAL(8,2),
    variacao_caixa DECIMAL(8,2) NOT NULL,
    criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT transacoes_clube_fk FOREIGN KEY (clube_id) REFERENCES clubes (id),
    CONSTRAINT transacoes_jogador_fk FOREIGN KEY (jogador_id) REFERENCES jogadores (id),
    CONSTRAINT transacoes_tipo_check CHECK (tipo IN ('COMPRA', 'VENDA'))
);

CREATE INDEX idx_transacoes_clube ON transacoes (clube_id);
CREATE INDEX idx_transacoes_jogador ON transacoes (jogador_id);
