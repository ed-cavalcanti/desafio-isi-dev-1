CREATE TABLE jogadores (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(100) NOT NULL,
    posicao VARCHAR(3) NOT NULL,
    agilidade INTEGER NOT NULL,
    idade INTEGER NOT NULL,
    valor_base DECIMAL(6,2) NOT NULL,
    condicao VARCHAR(20) NOT NULL,
    clube_id INTEGER,
    velocidade INTEGER NOT NULL,
    finalizacao INTEGER NOT NULL,
    passe INTEGER NOT NULL,
    drible INTEGER NOT NULL,
    defesa INTEGER NOT NULL,
    fisico INTEGER NOT NULL,
    potencial INTEGER NOT NULL,
    excluido_em TIMESTAMP,
    criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    atualizado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT jogadores_posicao_check CHECK (posicao IN ('GOL', 'ZAG', 'LAT', 'MEI', 'ATA')),
    CONSTRAINT jogadores_agilidade_check CHECK (agilidade BETWEEN 1 AND 100),
    CONSTRAINT jogadores_idade_check CHECK (idade BETWEEN 16 AND 45),
    CONSTRAINT jogadores_condicao_check CHECK (condicao IN ('APTO', 'MAL_CONDICIONADO', 'DOENTE')),
    CONSTRAINT jogadores_atributos_check CHECK (
        velocidade BETWEEN 1 AND 99
        AND finalizacao BETWEEN 1 AND 99
        AND passe BETWEEN 1 AND 99
        AND drible BETWEEN 1 AND 99
        AND defesa BETWEEN 1 AND 99
        AND fisico BETWEEN 1 AND 99
        AND potencial BETWEEN 1 AND 99
    )
);

CREATE INDEX idx_jogadores_clube_id ON jogadores (clube_id);
