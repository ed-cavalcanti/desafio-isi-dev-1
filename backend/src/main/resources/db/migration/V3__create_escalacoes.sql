CREATE TABLE escalacoes (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    clube_id INTEGER NOT NULL,
    formacao VARCHAR(5) NOT NULL,
    atualizado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT escalacoes_clube_uk UNIQUE (clube_id),
    CONSTRAINT escalacoes_clube_fk FOREIGN KEY (clube_id) REFERENCES clubes (id),
    CONSTRAINT escalacoes_formacao_check CHECK (formacao IN ('3-1', '2-2', '2-1-1', '1-2-1'))
);

CREATE TABLE escalacao_titulares (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    escalacao_id INTEGER NOT NULL,
    jogador_id INTEGER NOT NULL,
    CONSTRAINT escalacao_titulares_uk UNIQUE (escalacao_id, jogador_id),
    CONSTRAINT escalacao_titulares_escalacao_fk FOREIGN KEY (escalacao_id) REFERENCES escalacoes (id),
    CONSTRAINT escalacao_titulares_jogador_fk FOREIGN KEY (jogador_id) REFERENCES jogadores (id)
);
