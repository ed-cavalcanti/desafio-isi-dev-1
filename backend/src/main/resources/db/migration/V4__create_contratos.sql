CREATE TABLE contratos (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    jogador_id INTEGER NOT NULL,
    clube_id INTEGER NOT NULL,
    valor_compra DECIMAL(8,2) NOT NULL,
    fidelidade_ate TIMESTAMP NOT NULL,
    status VARCHAR(12) NOT NULL,
    criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    atualizado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT contratos_jogador_fk FOREIGN KEY (jogador_id) REFERENCES jogadores (id),
    CONSTRAINT contratos_clube_fk FOREIGN KEY (clube_id) REFERENCES clubes (id),
    CONSTRAINT contratos_status_check CHECK (status IN ('ATIVO', 'RESCINDIDO', 'ENCERRADO'))
);

CREATE INDEX idx_contratos_jogador ON contratos (jogador_id);
CREATE INDEX idx_contratos_clube ON contratos (clube_id);
