CREATE TABLE partidas (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mandante_clube_id INTEGER NOT NULL,
    visitante_clube_id INTEGER NOT NULL,
    gols_mandante INTEGER NOT NULL,
    gols_visitante INTEGER NOT NULL,
    resultado VARCHAR(9) NOT NULL,
    formacao_mandante VARCHAR(5) NOT NULL,
    formacao_visitante VARCHAR(5) NOT NULL,
    jogado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT partidas_mandante_fk FOREIGN KEY (mandante_clube_id) REFERENCES clubes (id),
    CONSTRAINT partidas_visitante_fk FOREIGN KEY (visitante_clube_id) REFERENCES clubes (id),
    CONSTRAINT partidas_resultado_check CHECK (resultado IN ('MANDANTE', 'VISITANTE', 'EMPATE')),
    CONSTRAINT partidas_placar_check CHECK (gols_mandante BETWEEN 0 AND 3 AND gols_visitante BETWEEN 0 AND 3)
);

CREATE INDEX idx_partidas_mandante ON partidas (mandante_clube_id);
CREATE INDEX idx_partidas_visitante ON partidas (visitante_clube_id);

CREATE TABLE duelos (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    partida_id INTEGER NOT NULL,
    ordem INTEGER NOT NULL,
    atacante_jogador_id INTEGER NOT NULL,
    atacante_nome VARCHAR(100) NOT NULL,
    atacante_posicao VARCHAR(3) NOT NULL,
    atacante_condicao VARCHAR(20) NOT NULL,
    atacante_atributo VARCHAR(11) NOT NULL,
    atacante_valor INTEGER NOT NULL,
    defensor_jogador_id INTEGER NOT NULL,
    defensor_nome VARCHAR(100) NOT NULL,
    defensor_posicao VARCHAR(3) NOT NULL,
    defensor_condicao VARCHAR(20) NOT NULL,
    defensor_atributo VARCHAR(11) NOT NULL,
    defensor_valor INTEGER NOT NULL,
    gol BOOLEAN NOT NULL,
    CONSTRAINT duelos_partida_fk FOREIGN KEY (partida_id) REFERENCES partidas (id),
    CONSTRAINT duelos_partida_uk UNIQUE (partida_id, ordem),
    CONSTRAINT duelos_ordem_check CHECK (ordem BETWEEN 1 AND 6),
    CONSTRAINT duelos_atacante_posicao_check CHECK (atacante_posicao IN ('GOL', 'ZAG', 'LAT', 'MEI', 'ATA')),
    CONSTRAINT duelos_defensor_posicao_check CHECK (defensor_posicao IN ('GOL', 'ZAG', 'LAT', 'MEI', 'ATA'))
);
