CREATE TABLE clubes (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(60) NOT NULL,
    nome_busca VARCHAR(60) NOT NULL,
    sigla VARCHAR(3) NOT NULL,
    caixa DECIMAL(8,2) NOT NULL,
    criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT clubes_nome_busca_uk UNIQUE (nome_busca),
    CONSTRAINT clubes_sigla_uk UNIQUE (sigla),
    CONSTRAINT clubes_caixa_check CHECK (caixa >= 0)
);

ALTER TABLE jogadores ADD CONSTRAINT jogadores_clube_fk FOREIGN KEY (clube_id) REFERENCES clubes (id);
